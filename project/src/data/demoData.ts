export function getRiskDistribution(assessments: Assessment[]) {
  const counts = { 'low risk': 0, 'mid risk': 0, 'high risk': 0 };
  assessments.forEach((a) => {
    counts[a.prediction] += 1;
  });
  return [
    { name: 'Low Risk', value: counts['low risk'], key: 'low risk' },
    { name: 'Mid Risk', value: counts['mid risk'], key: 'mid risk' },
    { name: 'High Risk', value: counts['high risk'], key: 'high risk' },
  ];
}

